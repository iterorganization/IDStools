@pytest.mark.parametrize(
    "version, message",
    [
        ("2.0.0", "Only DD 3 and DD 4"),
        ("5.0.0", "Only DD 3 and DD 4"),
        (None, "Only DD 3 and DD 4"),
        ("4.99.0", "not available"),
    ],
)
def test_unsupported_dd_version(entry, monkeypatch, version, message):
    monkeypatch.setattr(cs, "entry_dd_version", lambda entry, available: version)
    with pytest.raises(cs.SummaryError, match=message):
        cs.build_summary(entry)


def test_mixed_version_listing(tmp_path, factory_dd3, backend):
    """IDSs of a DD3 entry are found although the default DD is DD4."""
    uri = write_entry(tmp_path / "entry", factory_dd3, backend=backend)
    with imas.DBEntry(uri, "r") as entry:
        assert {"core_profiles", "equilibrium"} <= cs.entry_contents(entry)


def test_entry_without_data(tmp_path, backend):
    uri = entry_uri(tmp_path / "empty", backend)
    imas.DBEntry(uri, "w").close()
    # an empty netCDF file is not a valid data entry
    with pytest.raises(cs.SummaryError, match="Could not open" if backend == "netcdf" else "No IDS"):
        cs.build_summary(uri)


def test_source_ids():
    """Only the IDSs of the entry, referenced as paths, are inputs."""
    available = {"core_profiles", "core_sources", "equilibrium", "waves"}
    sources = [
        "equilibrium/time_slice/global_quantities/ip",
        "core_profiles/profiles_1d/electrons/density (line average on the horizontal chord through the magnetic "
        "axis, from equilibrium/time_slice/profiles_1d/r_inboard and r_outboard)",
        "core_profiles/profiles_1d/(electrons/pressure_thermal+pressure_ion_total) (3/2 volume integral)",
        "d/dt of summary/global_quantities/energy_thermal",
        "IPB98(y,2) scaling of summary/global_quantities/ip, ...",
        "summary/global_quantities/tau_energy / global_quantities/tau_energy_98",
        "core_sources/source[index=2]/global_quantities/power",
    ]
    assert cs.source_ids(sources, available) == ["core_profiles", "core_sources", "equilibrium"]


@pytest.mark.parametrize("version", ["3.38.1", "3.42.0", "4.0.0"])
def test_set_provenance(version):
    """reference[]/name in DD >= 3.42 (and DD4), sources in older DD3."""
    summary = imas.IDSFactory(version).summary()
    cs.set_provenance(summary, ["uri#equilibrium", "uri#core_profiles"])
    node = summary.ids_properties.provenance.node[0]
    if hasattr(node, "reference"):
        names = [str(reference.name) for reference in node.reference]
    else:
        names = list(node.sources)
    assert names == ["uri#equilibrium", "uri#core_profiles"]


