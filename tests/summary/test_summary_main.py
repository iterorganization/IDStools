SCRIPT = Path(__file__).resolve().parents[2] / "idstools" / "scripts" / "bin" / "create_summary"


HAS_IMAS_CORE = importlib.util.find_spec("imas_core") is not None
# netCDF entries need no IMAS-Core; HDF5 entries are only tested with it
BACKENDS = [
    "netcdf",
    pytest.param("hdf5", marks=pytest.mark.skipif(not HAS_IMAS_CORE, reason="IMAS-Core is not installed")),
]


def entry_uri(path, backend):
    return f"{path}.nc" if backend == "netcdf" else f"imas:hdf5?path={path}"


@pytest.fixture(params=BACKENDS)
def backend(request):
    return request.param


def write_entry(path, factory, with_summary=False, backend="netcdf", ion_temperature=False):
    """Create a data entry with core_profiles and equilibrium."""
    uri = entry_uri(path, backend)
    with imas.DBEntry(uri, "w", dd_version=factory.dd_version) as entry:
        cp = make_core_profiles(factory)
        cp.code.name = "test-code"
        if ion_temperature:  # gives the thermal energy, and quantities derived from it
            for profile in cp.profiles_1d:
                profile.t_i_average = profile.electrons.temperature
        entry.put(cp)

        eq = factory.equilibrium()
        eq.ids_properties.homogeneous_time = 1
        eq.time = np.array([0.0, 2.0])
        eq.vacuum_toroidal_field.r0 = 6.2
        eq.vacuum_toroidal_field.b0 = np.array([-5.3, -5.3])
        eq.time_slice.resize(2)
        for ts, t, ip in zip(eq.time_slice, eq.time, (-1e6, -3e6), strict=True):
            ts.time = t
            ts.global_quantities.ip = ip
        entry.put(eq)

        if with_summary:
            summary = factory.summary()
            summary.ids_properties.homogeneous_time = 1
            summary.ids_properties.comment = "original summary"
            summary.time = np.array([0.0])
            entry.put(summary)
    return uri


def read_summary(uri):
    with imas.DBEntry(uri, "r") as entry:
        return entry.get("summary", autoconvert=False)


